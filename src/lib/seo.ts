  'Plain-English UK home-buying calculators. The maths of moving in.';

/** "Sources | House Sums"; just "House Sums" with no page title (the home page). */
export function fullTitle(title?: string): string {
  return title ? `${title} | ${SITE_NAME}` : SITE_NAME;
}

