/**
 * SEO helpers (phase 5): titles, descriptions, canonical and absolute URLs, Open Graph image
 * paths and JSON-LD builders. Pure: no DOM, no JSON imports, no Astro globals, so it is unit
 * tested in seo.test.ts and used by Base.astro and the pages alike.
 *
 * Contract for pages: pass `title` (without the site name) and `description` to Base as before;
 * optionally `ogImage` (a site-relative path from ogImagePath()) and `jsonLd` (one object or a
 * list, from the builders below). Base adds the site name, canonical link, Open Graph and
 * Twitter tags and the JSON-LD script.
 *
 * Trailing-slash policy (docs/decisions.md, "Tooling (phase 1)"): page URLs end in "/", files
 * do not. canonicalUrl() applies it whatever the request path looks like.
 */
import type { Nation } from './types';
import { NATION_NAMES, NATION_SLUGS } from './nations';

export const SITE_NAME = 'House Sums';

/** Used when a page passes no description. */
