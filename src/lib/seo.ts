/** A page path with the trailing slash policy applied (files keep their extension). */
export function withTrailingSlash(pathname: string): string {
  const last = pathname.split('/').pop() ?? '';
  if (pathname.endsWith('/') || /\.[a-z0-9]+$/i.test(last)) return pathname;
  return `${pathname}/`;
}

/**
 * Absolute canonical URL for a page: `pathname` is the full path including the base (Astro's
 * Astro.url.pathname, or a url() result), `site` is Astro.site. Query and hash are dropped.
 */
export function canonicalUrl(pathname: string, site: URL | string): string {
  const clean = pathname.split(/[?#]/)[0] ?? '/';
  return new URL(withTrailingSlash(clean === '' ? '/' : clean), site).href;
}

/** Absolute URL for any path that already includes the base (a url() result). */
export function absoluteUrl(path: string, site: URL | string): string {
  return new URL(path, site).href;
}

