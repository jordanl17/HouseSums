/** Alt text for the OG image. */
export function ogImageAlt(nation?: Nation | null): string {
  return nation
    ? `House Sums: rent v buy in ${NATION_NAMES[nation]}`
    : 'House Sums: the maths of moving in';
}

// ---------------------------------------------------------------------------------------------
// JSON-LD (schema.org). Builders return plain objects; Base serialises them with jsonLdText().
// ---------------------------------------------------------------------------------------------

export type JsonLd = Record<string, unknown>;

/** WebApplication for pages that carry the calculator (home and area pages). */
export function webApplicationLd(input: {
  name: string;
  /** Absolute URL of the page. */
  url: string;
  description?: string;
}): JsonLd {
  const ld: JsonLd = {
    '@context': 'https://schema.org',
    '@type': 'WebApplication',
    name: input.name,
    url: input.url,
    applicationCategory: 'FinanceApplication',
    operatingSystem: 'Any',
    offers: { '@type': 'Offer', price: '0', priceCurrency: 'GBP' },
  };
  if (input.description) ld['description'] = input.description;
  return ld;
}

/** BreadcrumbList from the home page down to the current page. URLs must be absolute. */
export function breadcrumbLd(items: readonly { name: string; url: string }[]): JsonLd {
  return {
    '@context': 'https://schema.org',
    '@type': 'BreadcrumbList',
    itemListElement: items.map((item, index) => ({
      '@type': 'ListItem',
      position: index + 1,
      name: item.name,
      item: item.url,
    })),
  };
}

/**
 * JSON for a <script type="application/ld+json"> body. "<" is escaped so a value can never
 * close the script element; the JSON stays valid.
 */
export function jsonLdText(data: JsonLd | readonly JsonLd[]): string {
  return JSON.stringify(data).replace(/</g, '\\u003c');
}
